#!/usr/bin/env python3
"""
packager_agent.py

Goal:
- Take a bundle that has already been validated by Intake Agent
- Create an OpenROAD-flow-scripts runnable design directory:
    $ORFS_DIR/flow/designs/<platform>/<design_name>/
      - config.mk
      - constraint.sdc
      - src/<rtl>

Outputs a machine-readable packager_report.json plus helper files to run the flow.

Usage:
  python packager_agent.py \
    --bundle_dir /path/to/frontend_bundle \
    --intake_report /path/to/intake_out/<bundle_name>/intake_report.json

Optional:
  --env_file .env
  --design_name config_regs
  --platform sky130hd
  --clock_port clk
  --clock_period_ns 5.0
  --out_dir /path/to/package_out
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
from dataclasses import dataclass, asdict
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple


# ----------------------------
# .env loader (no dependencies)
# (kept intentionally similar to intake_agent.py)
# ----------------------------

def load_env_file(env_path: Path) -> None:
    if not env_path.exists():
        return
    for raw_line in env_path.read_text().splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        k = k.strip()
        v = v.strip().strip('"').strip("'").strip()
        os.environ.setdefault(k, v)


# ----------------------------
# Findings / report structures
# ----------------------------

@dataclass
class Finding:
    severity: str  # "ERROR" | "WARNING" | "INFO"
    code: str
    message: str
    fix: str


def add_finding(lst: List[Finding], severity: str, code: str, message: str, fix: str) -> None:
    lst.append(Finding(severity=severity, code=code, message=message, fix=fix))


def status_from_findings(errors: List[Finding], warnings: List[Finding]) -> str:
    if errors:
        return "FAIL"
    if warnings:
        return "PASS_WITH_WARNINGS"
    return "PASS"


def write_json(path: Path, obj: Any) -> None:
    path.write_text(json.dumps(obj, indent=2))


def write_text(path: Path, s: str) -> None:
    path.write_text(s if s.endswith("\n") else (s + "\n"), encoding="utf-8")


# ----------------------------
# Bundle/manifest discovery (same preference order as intake)
# ----------------------------

def find_manifest_json(bundle_dir: Path) -> Optional[Path]:
    direct = bundle_dir / "manifest.json"
    if direct.exists():
        return direct
    exact = list(bundle_dir.glob("*_manifest.json"))
    if exact:
        return sorted(exact, key=lambda p: len(p.name))[0]
    broad = list(bundle_dir.glob("*manifest*.json"))
    if broad:
        return sorted(broad, key=lambda p: len(p.name))[0]
    return None


# ----------------------------
# Helpers: infer clock/reset from manifest
# ----------------------------

def infer_clock_reset(manifest: Dict[str, Any]) -> Tuple[Optional[str], Optional[str]]:
    clock_port = None
    reset_port = None
    ports = manifest.get("ports", {})
    clock_reset = ports.get("clock_reset", [])
    if not isinstance(clock_reset, list):
        return None, None

    for p in clock_reset:
        if not isinstance(p, dict):
            continue
        n = p.get("name")
        d = p.get("dir")
        if not isinstance(n, str) or d != "input":
            continue
        ln = n.lower()
        if clock_port is None and "clk" in ln:
            clock_port = n
        if reset_port is None and ("rst" in ln or "reset" in ln):
            reset_port = n
    return clock_port, reset_port


def safe_design_name(s: str) -> str:
    # ORFS design dirs are happiest with [A-Za-z0-9_]
    s = s.strip()
    s = re.sub(r"[^A-Za-z0-9_]+", "_", s)
    return s or "design"


# ----------------------------
# RTL normalization
# ----------------------------

# Share of the clock period budgeted to logic outside the block on every input and
# output (ORFS convention, as in flow/designs/sky130hd/gcd and ibex). Without it only
# register-to-register paths are timed and paths through ports go unchecked.
SDC_IO_DELAY_PCT = 0.2


def build_sdc(module_name: str, clock_port: str, clock_period_ns: float,
              io_pct: float = SDC_IO_DELAY_PCT) -> str:
    """
    constraint.sdc for one block, in the ORFS style: the period lives in
    `set clk_period`, which create_clock and the I/O delays both use.
    pipeline.py _patch_clock_period rewrites that line when the Fmax tuner runs.
    """
    return (
        "# Auto-generated by packager_agent.py (ORFS convention, as in designs/sky130hd/gcd)\n"
        f"current_design {module_name}\n"
        "\n"
        "set clk_name core_clk\n"
        f"set clk_port_name {clock_port}\n"
        f"set clk_period {clock_period_ns}\n"
        f"set clk_io_pct {io_pct}\n"
        "\n"
        "set clk_port [get_ports $clk_port_name]\n"
        "\n"
        "create_clock -name $clk_name -period $clk_period $clk_port\n"
        "\n"
        "# Budget part of the period to logic outside this block on every port, so\n"
        "# paths through ports are timed, not only register-to-register paths.\n"
        "set non_clock_inputs [all_inputs -no_clocks]\n"
        "\n"
        "set_input_delay [expr $clk_period * $clk_io_pct] -clock $clk_name $non_clock_inputs\n"
        "set_output_delay [expr $clk_period * $clk_io_pct] -clock $clk_name [all_outputs]\n"
    )


def _rtl_needs_slang(rtl_path: Path) -> bool:
    """
    Returns True if the RTL contains SystemVerilog constructs that require
    the slang frontend — specifically unpacked array port dimensions,
    type cast syntax, or struct/aggregate literals.
    """
    try:
        text = rtl_path.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return False
    # Strip single-line comments before matching so trailing // don't interfere
    stripped = re.sub(r"//.*$", "", text, flags=re.MULTILINE)
    # Unpacked array port dimensions e.g. "input logic [W-1:0] port_name [DEPTH]"
    unpacked_port_re = re.compile(
        r"^\s*(input|output|inout)\b.*\b\w+\s*\[\w+\]\s*[,;)]?\s*$",
        re.MULTILINE | re.IGNORECASE,
    )
    if unpacked_port_re.search(stripped):
        return True
    # SystemVerilog type cast e.g. "int'(x)" or "logic'(x)"
    typecast_re = re.compile(
        r"\b(int|logic|bit|byte|shortint|longint|integer|time)\s*'\s*\(",
        re.MULTILINE,
    )
    if typecast_re.search(stripped):
        return True
    # SystemVerilog aggregate/struct literals e.g. "'{data: x, mask: y}" or "'0"
    aggregate_re = re.compile(
        r"'\s*[\{0-9]",
        re.MULTILINE,
    )
    if aggregate_re.search(stripped):
        return True
    return False


def _split_line_comment(line: str) -> Tuple[str, str]:
    """
    Split a source line into (code, comment) at its trailing `//`.

    Used by _normalize_rtl so line-joining decisions are made on code alone.
    Does not honour `//` inside a string literal, which does not occur in a
    port declaration.
    """
    idx = line.find("//")
    if idx < 0:
        return line, ""
    return line[:idx], line[idx:]


def _normalize_rtl(rtl_path: Path) -> None:
    """
    Normalize RTL formatting issues that trip up Yosys:

    1. Join split port declarations — when a port direction keyword
       (input/output/inout) appears on a line with no following identifier,
       the port name is on the next line. Join them onto one line.

       Before:
           input  logic [DEPTH-1:0]
           q_valid,
       After:
           input  logic [DEPTH-1:0] q_valid,

    2. Strip Windows CRLF line endings.
    """
    try:
        text = rtl_path.read_text(encoding="utf-8", errors="ignore")
    except Exception as e:
        print(f"[packager] WARNING: could not read RTL for normalization: {e}")
        return

    lines = text.splitlines()
    normalized: List[str] = []
    i = 0
    port_dir_re = re.compile(r"^\s*(input|output|inout)\b", re.IGNORECASE)
    # A port declaration is UNFINISHED — its identifier is on the next line —
    # when its code portion ends in a packed range or a bare type keyword.
    # Anything else (an identifier, a comma, a close-paren) means the
    # declaration is complete and must NOT be joined.
    #
    # Matched against code only. The previous pattern tested the raw line for
    # the *presence* of an identifier, which a trailing comment like
    # "// {cs_n, ras_n, cas_n, we_n}" defeated: the line looked unfinished, the
    # next port was joined onto the unterminated "//", and that port was
    # silently deleted from the design.
    needs_join_re = re.compile(
        r"(\]|\b(?:logic|wire|reg|bit|signed|unsigned|int|integer|byte))\s*$",
        re.IGNORECASE,
    )

    while i < len(lines):
        line = lines[i]
        code, comment = _split_line_comment(line)
        # A port direction line whose identifier is still on the next line
        if port_dir_re.match(code) and needs_join_re.search(code.rstrip()):
            # Peek at next non-empty line and join it
            j = i + 1
            while j < len(lines) and not lines[j].strip():
                j += 1
            if j < len(lines):
                next_code, next_comment = _split_line_comment(lines[j])
                # Comments are re-emitted AFTER the joined code. Appending the
                # next line onto an unterminated "//" would comment it out.
                tails = [c[2:].strip() for c in (comment, next_comment) if c]
                tails = [t for t in tails if t]
                tail = ("  // " + "  ".join(tails)) if tails else ""
                joined = code.rstrip() + " " + next_code.strip() + tail
                normalized.append(joined)
                i = j + 1
                continue
        normalized.append(line)
        i += 1

    result = "\n".join(normalized) + "\n"
    try:
        rtl_path.write_text(result, encoding="utf-8")
    except Exception as e:
        print(f"[packager] WARNING: could not write normalized RTL: {e}")


