def package_bundle(
    bundle_dir: Path,
    intake_report_path: Path,
    out_dir: Path,
    orfs_dir: Optional[Path],
    design_name: Optional[str],
    platform: Optional[str],
    clock_port: Optional[str],
    clock_period_ns: Optional[float],
) -> Dict[str, Any]:
    errors: List[Finding] = []
    warnings: List[Finding] = []
    infos: List[Finding] = []
    facts: Dict[str, Any] = {}

    facts["bundle_dir"] = str(bundle_dir)
    facts["intake_report_path"] = str(intake_report_path)
    facts["out_dir"] = str(out_dir)
    facts["env"] = {
        "ORFS_DIR": os.environ.get("ORFS_DIR", "").strip(),
        "OUT_ROOT": os.environ.get("OUT_ROOT", "").strip(),
        "PLATFORM": os.environ.get("PLATFORM", "").strip(),
        "MAKE_JOBS": os.environ.get("MAKE_JOBS", "").strip(),
    }

    if not bundle_dir.exists():
        add_finding(errors, "ERROR", "IO-001", f"Bundle dir not found: {bundle_dir}", "Pass the correct --bundle_dir.")
        return _finalize(errors, warnings, infos, facts, packaged=None)

    if not intake_report_path.exists():
        add_finding(errors, "ERROR", "IO-002", f"Intake report not found: {intake_report_path}", "Pass the correct --intake_report.")
        return _finalize(errors, warnings, infos, facts, packaged=None)

    # Load intake report and enforce gating
    try:
        intake = json.loads(intake_report_path.read_text())
    except Exception as e:
        add_finding(errors, "ERROR", "INTAKE-001", f"Failed to parse intake_report.json: {e}", "Regenerate intake outputs.")
        return _finalize(errors, warnings, infos, facts, packaged=None)

    intake_status = intake.get("status")
    facts["intake_status"] = intake_status

    if intake_status not in ("PASS", "PASS_WITH_WARNINGS"):
        add_finding(
            errors, "ERROR", "INTAKE-010",
            f"Refusing to package because intake status is {intake_status!r} (must be PASS or PASS_WITH_WARNINGS).",
            "Fix the intake errors first, then re-run packager."
        )
        return _finalize(errors, warnings, infos, facts, packaged=None)

    # Load manifest
    manifest_path = find_manifest_json(bundle_dir)
    if not manifest_path:
        add_finding(errors, "ERROR", "MAN-001", "No manifest JSON found in bundle.", "Include manifest.json or *_manifest.json.")
        return _finalize(errors, warnings, infos, facts, packaged=None)

    try:
        manifest = json.loads(manifest_path.read_text())
    except Exception as e:
        add_finding(errors, "ERROR", "MAN-002", f"Manifest JSON parse failed: {e}", "Fix manifest formatting.")
        return _finalize(errors, warnings, infos, facts, packaged=None)

    # Basic required keys (intake should have enforced, but keep packager robust)
    if "file" not in manifest or "module_name" not in manifest:
        add_finding(errors, "ERROR", "MAN-010", "Manifest missing 'file' and/or 'module_name'.", "Regenerate manifest via frontend.")
        return _finalize(errors, warnings, infos, facts, packaged=None)

    rtl_files = manifest["file"] if isinstance(manifest["file"], list) else [manifest["file"]]
    rtl_files = [str(f).strip() for f in rtl_files]
    rtl_paths = [bundle_dir / f for f in rtl_files]
    missing = [str(p) for p in rtl_paths if not p.exists()]
    if missing:
        add_finding(errors, "ERROR", "IO-010", f"RTL file(s) not found: {missing}",
                    "Ensure the bundle contains every file listed in manifest.file.")
        return _finalize(errors, warnings, infos, facts, packaged=None)
    names = [p.name for p in rtl_paths]
    dupes = sorted({n for n in names if names.count(n) > 1})
    if dupes:
        add_finding(errors, "ERROR", "IO-011", f"manifest.file lists several sources with the same filename: {dupes}",
                    "Give every source a unique filename; they are copied into one src/ directory.")
        return _finalize(errors, warnings, infos, facts, packaged=None)
    rtl_path = rtl_paths[0]

    # Resolve platform
    resolved_platform = (
        platform
        or manifest.get("platform")
        or (os.environ.get("PLATFORM") or "").strip()
        or None
    )
    if not resolved_platform:
        add_finding(errors, "ERROR", "OR-001", "No PLATFORM resolved.", "Pass --platform, set PLATFORM in .env, or add manifest.platform.")
        return _finalize(errors, warnings, infos, facts, packaged=None)

    # Resolve design name
    resolved_design_name = safe_design_name(design_name or bundle_dir.name)

    # Resolve clock/reset inference
    inferred_clk, inferred_rst = infer_clock_reset(manifest)

    resolved_clock_port = clock_port or manifest.get("clock_port") or inferred_clk
    resolved_reset_port = manifest.get("reset_port") or inferred_rst  # informational only

    # Resolve clock period
    defaulted_clock_period = False
    if clock_period_ns is not None:
        resolved_clock_period = float(clock_period_ns)
    elif manifest.get("clock_period_ns") is not None:
        resolved_clock_period = float(manifest["clock_period_ns"])
    else:
        resolved_clock_period = 10.0  # default policy
        defaulted_clock_period = True
        add_finding(
            warnings, "WARNING", "OR-003",
            "clock_period_ns not provided; defaulting to 10.0 ns.",
            "Add manifest.clock_period_ns (or pass --clock_period_ns) to control timing constraints."
        )

    if not resolved_clock_port:
        add_finding(
            warnings, "WARNING", "OR-002",
            "Clock port not identified; constraint.sdc will be generated without a create_clock.",
            "Add manifest.clock_port or ensure manifest.ports.clock_reset includes the clock."
        )

    # Resolve ORFS_DIR
    resolved_orfs_dir = orfs_dir or Path((os.environ.get("ORFS_DIR") or "").strip()) if (os.environ.get("ORFS_DIR") or "").strip() else None
    if not resolved_orfs_dir:
        add_finding(
            errors, "ERROR", "ORFS-001",
            "ORFS_DIR not set/provided; cannot create ORFS design directory.",
            "Set ORFS_DIR in .env or pass --orfs_dir."
        )
        return _finalize(errors, warnings, infos, facts, packaged=None)

    flow_dir = resolved_orfs_dir / "flow"
    makefile = flow_dir / "Makefile"
    if not makefile.exists():
        add_finding(
            errors, "ERROR", "ORFS-002",
            f"ORFS flow Makefile not found at: {makefile}",
            "Ensure ORFS_DIR points to the root of OpenROAD-flow-scripts."
        )
        return _finalize(errors, warnings, infos, facts, packaged=None)

    # Create ORFS design directory
    design_dir = flow_dir / "designs" / resolved_platform / resolved_design_name
    src_dir = design_dir / "src"
    src_dir.mkdir(parents=True, exist_ok=True)

    # Copy every source into src/ and normalize formatting
    dst_rtl_paths = []
    for src_path in rtl_paths:
        dst = src_dir / src_path.name
        shutil.copy2(src_path, dst)
        _normalize_rtl(dst)
        dst_rtl_paths.append(dst)
    dst_rtl_path = dst_rtl_paths[0]

    # Any source needing full SystemVerilog elaboration (unpacked array ports, type
    # casts, aggregate literals) puts the whole design on the slang frontend.
    slang_sources = [p.name for p in dst_rtl_paths if _rtl_needs_slang(p)]
    needs_slang = bool(slang_sources)
    if needs_slang:
        print(f"[packager] SystemVerilog constructs needing slang found in {slang_sources} — "
              f"enabling the slang SV frontend.")

    # Generate constraint.sdc
    sdc_path = design_dir / "constraint.sdc"
    if resolved_clock_port:
        sdc = build_sdc(str(manifest.get("module_name")), resolved_clock_port, resolved_clock_period)
    else:
        sdc = (
            "# Auto-generated by packager_agent.py\n"
            "# NOTE: clock port unknown; add create_clock once clock_port is known.\n"
        )
    write_text(sdc_path, sdc)

    # Generate config.mk (minimal, runner can override via make vars if desired)
    config_mk_path = design_dir / "config.mk"
    # Use forward slashes for make friendliness
    verilog_rel = f"designs/{resolved_platform}/{resolved_design_name}/src/{dst_rtl_path.name}"
    sdc_rel = f"designs/{resolved_platform}/{resolved_design_name}/{sdc_path.name}"

    config_lines = [
        "# Auto-generated by packager_agent.py",
        f"export DESIGN_NAME = {manifest.get('module_name')}",
        f"export PLATFORM = {resolved_platform}",
        "export VERILOG_FILES = " + " ".join(
            f"/OpenROAD-flow-scripts/flow/designs/{resolved_platform}/{resolved_design_name}/src/{p.name}"
            for p in dst_rtl_paths),
        f"export SDC_FILE      = /OpenROAD-flow-scripts/flow/designs/{resolved_platform}/{resolved_design_name}/constraint.sdc",
        f"export CLOCK_PERIOD  = {resolved_clock_period}",
        f"export CORE_UTILIZATION = 20",
        f"export CORE_MARGIN = 10",
        f"export TNS_END_PERCENT = 100",
        f"export ANTENNA_REPAIR = 1",
    ]
    if needs_slang:
        config_lines.append("export SYNTH_HDL_FRONTEND = slang")
    if resolved_clock_port:
        config_lines.append(f"export CLOCK_PORT = {resolved_clock_port}")
    # Flow settings this design needs, declared by the manifest (e.g. SYNTH_ARGS).
    orfs_config = manifest.get("orfs_config") or {}
    if isinstance(orfs_config, dict) and orfs_config:
        config_lines.append("# From manifest.orfs_config")
        config_lines += [f"export {k} = {v}" for k, v in orfs_config.items()]
        print(f"[packager] Applied manifest.orfs_config: {orfs_config}")
    config_lines = [l for l in config_lines if l]
    write_text(config_mk_path, "\n".join(config_lines) + "\n")

    # Write packaging outputs
    out_dir.mkdir(parents=True, exist_ok=True)

    packaged_manifest = dict(manifest)
    packaged_manifest["packager"] = {
        "resolved": {
            "platform": resolved_platform,
            "design_name": resolved_design_name,
            "rtl_filename": rtl_path.name,
            "rtl_files": [p.name for p in dst_rtl_paths],
            "orfs_config": orfs_config,
            "clock_port": resolved_clock_port,
            "reset_port": resolved_reset_port,
            "clock_period_ns": resolved_clock_period,
            "sdc_io_delay_pct": SDC_IO_DELAY_PCT if resolved_clock_port else None,
            "orfs_dir": str(resolved_orfs_dir),
            "orfs_design_dir": str(design_dir),
            "design_config_mk": str(config_mk_path),
        },
        "policy": {
            "clock_period_defaulted": defaulted_clock_period,
        },
    }

    write_json(out_dir / "packaged_manifest.json", packaged_manifest)
    write_text(out_dir / "orfs_design_path.txt", str(design_dir))

    # Convenience script for your future runner (and for you now)
    jobs = (os.environ.get("MAKE_JOBS") or "").strip()
    jobs_arg = jobs if jobs.startswith("-j") else (f"-j{jobs}" if jobs else "")
    rel_cfg = f"designs/{resolved_platform}/{resolved_design_name}/config.mk"
    run_sh = (
        "#!/usr/bin/env bash\n"
        "set -euo pipefail\n\n"
        f"cd {flow_dir}\n"
        f"make {jobs_arg} DESIGN_CONFIG={rel_cfg}\n"
    )
    run_path = out_dir / "run_in_orfs.sh"
    write_text(run_path, run_sh)
    try:
        os.chmod(run_path, 0o755)
    except Exception:
        pass

    readme = (
        f"# Packaged OpenROAD Design: {resolved_design_name}\n\n"
        "This directory was generated by `packager_agent.py`.\n\n"
        "## Where the ORFS design lives\n"
        f"- `{design_dir}`\n\n"
        "## How to run (manual)\n"
        "```bash\n"
        f"cd {flow_dir}\n"
        f"make {jobs_arg} DESIGN_CONFIG=designs/{resolved_platform}/{resolved_design_name}/config.mk\n"
        "```\n\n"
        "## Notes\n"
        f"- RTL copied to: `{dst_rtl_path}`\n"
        f"- SDC: `{sdc_path}`\n"
        f"- Config: `{config_mk_path}`\n"
    )
    write_text(out_dir / "README.md", readme)

    facts.update({
        "resolved_platform": resolved_platform,
        "resolved_design_name": resolved_design_name,
        "rtl_src": str(rtl_path),
        "rtl_dst": str(dst_rtl_path),
        "design_dir": str(design_dir),
        "config_mk_path": str(config_mk_path),
        "sdc_path": str(sdc_path),
        "defaulted_clock_period": defaulted_clock_period,
    })

    add_finding(infos, "INFO", "OK-001", "Packaging completed and ORFS design directory created.", "You can now run make with DESIGN_CONFIG=...")

    return _finalize(errors, warnings, infos, facts, packaged=packaged_manifest)


def _finalize(errors: List[Finding], warnings: List[Finding], infos: List[Finding], facts: Dict[str, Any], packaged: Optional[Dict[str, Any]]) -> Dict[str, Any]:
    status = status_from_findings(errors, warnings)
    return {
        "status": status,
        "errors": [asdict(e) for e in errors],
        "warnings": [asdict(w) for w in warnings],
        "info": [asdict(i) for i in infos],
        "facts": facts,
        "packaged_manifest": packaged,
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--bundle_dir", required=True, type=Path)
    ap.add_argument("--intake_report", required=True, type=Path)
    ap.add_argument("--env_file", type=Path, default=Path(".env"))
    ap.add_argument("--out_dir", type=Path, default=None)

    ap.add_argument("--orfs_dir", type=Path, default=None)
    ap.add_argument("--design_name", type=str, default=None)
    ap.add_argument("--platform", type=str, default=None)
    ap.add_argument("--clock_port", type=str, default=None)
    ap.add_argument("--clock_period_ns", type=float, default=None)

    args = ap.parse_args()

    load_env_file(args.env_file)

    if args.out_dir is None:
        out_root = (os.environ.get("OUT_ROOT") or "").strip()
        if out_root:
            args.out_dir = Path(out_root) / "package" / args.bundle_dir.name
        else:
            args.out_dir = Path("./package_out") / args.bundle_dir.name

    result = package_bundle(
        bundle_dir=args.bundle_dir,
        intake_report_path=args.intake_report,
        out_dir=args.out_dir,
        orfs_dir=args.orfs_dir,
        design_name=args.design_name,
        platform=args.platform,
        clock_port=args.clock_port,
        clock_period_ns=args.clock_period_ns,
    )

    # Always write report
    args.out_dir.mkdir(parents=True, exist_ok=True)
    write_json(args.out_dir / "packager_report.json", {
        "status": result["status"],
        "errors": result["errors"],
        "warnings": result["warnings"],
        "info": result["info"],
        "facts": result["facts"],
    })

    # Exit codes similar to intake
    if result["status"] == "PASS":
        return 0
    if result["status"] == "PASS_WITH_WARNINGS":
        return 1
    return 2


